#!/usr/bin/env bash
# stamp_run.sh — отметка о ЗАВЕРШЁННОМ прогоне автономной задачи.
#
# ЗАЧЕМ. Задача планировщика может стартовать, что-то сделать и зависнуть, не дойдя
# до конца. Всё, что смотрит на «стартовала ли задача» (отметка планировщика, время
# правки тронутого файла), в этот момент видит живого агента. Живого агента там нет.
#
# ПРАВИЛО, из которого сделан скрипт: детектор смотрит на запись, которую делает сам
# исполнитель В МОМЕНТ УСПЕХА. Поэтому вызов — ПОСЛЕДНЯЯ строка задачи: не дошёл до
# неё — значит прогон не состоялся, и встречный сторож обязан это заметить.
#
# Использование (последним шагом задачи):
#   bash "System/scripts/stamp_run.sh" daily-audit
#
# Куда пишет: System/state/runs/<имя>.txt — первая строка ГГГГ-ММ-ДД ЧЧ:ММ, дальше
# короткая история последних 30 прогонов. Папка System/state/ — локальный факт этой
# машины, её место в .gitignore.
set -euo pipefail

NAME="${1:?нужно имя задачи, например: daily-audit}"
case "$NAME" in
  *[!a-zA-Z0-9._-]*) echo "имя задачи только из a-z0-9._-" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DIR="$ROOT/System/state/runs"
FILE="$DIR/$NAME.txt"
mkdir -p "$DIR"

STAMP="$(date '+%Y-%m-%d %H:%M')"
# Свежая отметка — первой строкой (её читают сторожа), история — под ней.
{ echo "$STAMP"; [ -f "$FILE" ] && head -30 "$FILE"; } > "$FILE.new" 2>/dev/null || echo "$STAMP" > "$FILE.new"
mv "$FILE.new" "$FILE"
echo "отмечен прогон: $NAME $STAMP"
